import fs from 'node:fs/promises'
import path from 'node:path'
import { expect, test } from '../fixtures/electron.mjs'

async function createSpace(app, page, directory) {
  await app.evaluate(({ dialog }, directory) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] })
  }, directory)
  const section = page.locator('[data-row-key="section:spaces"]')
  await section.locator('.desktop-task-sidebar__section-heading').hover()
  await section.locator('.desktop-task-sidebar__section-add').click()
  const spaceDialog = page.locator('.desktop-space-dialog')
  await spaceDialog.getByPlaceholder('输入空间名称').fill('文件树验收')
  await spaceDialog.getByRole('button', { name: '选择目录', exact: true }).click()
  await spaceDialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(spaceDialog).toBeHidden()
}

test('file explorer preserves edits and undo through rename, rejects copy conflicts and watches external changes', async ({ buddy }) => {
  const instance = await buddy.createInstance('file-explorer')
  const directory = path.join(instance.home, 'documents')
  await fs.mkdir(path.join(directory, 'src'), { recursive: true })
  await fs.writeFile(path.join(directory, 'README.md'), 'Original document.\n')
  await Promise.all(Array.from({ length: 251 }, (_, index) => fs.writeFile(path.join(directory, 'src', `${String(index).padStart(3, '0')}.ts`), 'export const value = 1\n')))
  const { app, page, diagnostics } = await instance.launch()
  await createSpace(app, page, directory)
  await page.locator('.desktop-workbench-area__tasks .tiptap').click()
  await page.keyboard.press('Control+Shift+P')
  await page.getByPlaceholder('输入命令名称').fill('文件')
  await page.getByPlaceholder('输入命令名称').press('Enter')
  const tree = page.getByTestId('context-file-tree')
  const row = name => tree.locator(`[data-path="${name}"]`)
  await expect(row('README.md')).toBeVisible()
  await page.getByTestId('context-panel-maximize').click()
  await row('src').click()
  await expect(row('src/000.ts')).toBeVisible()
  await tree.press('End')
  await expect(tree).toHaveAttribute('aria-activedescendant', await row('README.md').getAttribute('id'))
  await tree.press('ArrowUp')
  await expect(row('src/250.ts')).toBeVisible()
  await tree.press('Home')
  await tree.press('ArrowLeft')
  await row('README.md').click()
  await page.getByTestId('document-mode-edit').click()
  let editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Original document.')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Unsaved change.\n')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  async function rename() {
    await row('README.md').click({ button: 'right' })
    await page.locator('.n-dropdown-menu:visible').getByText('重命名', { exact: true }).click()
    const modal = page.locator('.explorer-name-dialog')
    await modal.getByRole('textbox', { name: '名称' }).fill('RENAMED.md')
    await modal.getByRole('button', { name: '确定', exact: true }).click()
  }
  await rename()
  await page.locator('.n-dialog').filter({ hasText: '先保存打开的文件' }).getByRole('button', { name: '取消', exact: true }).click()
  await expect(row('README.md')).toBeVisible()
  expect(await fs.readFile(path.join(directory, 'README.md'), 'utf8')).toBe('Original document.\n')
  await page.locator('.explorer-name-dialog').getByRole('button', { name: '确定', exact: true }).click()
  await page.getByRole('button', { name: '保存并继续', exact: true }).click()
  await expect(row('RENAMED.md')).toBeVisible()
  await expect.poll(() => fs.readFile(path.join(directory, 'RENAMED.md'), 'utf8')).toContain('Unsaved change.')
  await expect.poll(() => fs.access(path.join(directory, 'README.md')).then(() => true, () => false)).toBe(false)
  editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Unsaved change.')
  const beforeUndo = await fs.readFile(path.join(directory, 'RENAMED.md'), 'utf8')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+z')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  await page.keyboard.press('Control+s')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'false')
  const afterUndo = await fs.readFile(path.join(directory, 'RENAMED.md'), 'utf8')
  expect(afterUndo).not.toBe(beforeUndo)
  await row('RENAMED.md').click()
  await tree.press('Control+c')
  await row('src').click()
  await tree.press('Control+v')
  await expect.poll(() => fs.readFile(path.join(directory, 'src', 'RENAMED.md'), 'utf8').catch((error) => {
    if (error.code === 'ENOENT')
      return null
    throw error
  })).toBe(afterUndo)
  await expect(page.getByRole('button', { name: '新建文件夹', exact: true })).toBeEnabled()
  await tree.press('Control+v')
  await expect(page.getByText('目标已存在或文件已更改，请刷新后重试。', { exact: true })).toBeVisible()
  expect(await fs.readFile(path.join(directory, 'src', 'RENAMED.md'), 'utf8')).toBe(afterUndo)
  await page.getByRole('button', { name: '全部折叠', exact: true }).click()
  await fs.writeFile(path.join(directory, 'external.txt'), 'watched')
  await expect(row('external.txt')).toBeVisible()
  await row('RENAMED.md').click()
  await page.getByTestId('document-mode-edit').click()
  editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Original document.')
  await fs.writeFile(path.join(directory, 'RENAMED.md'), 'Changed outside.\n')
  await expect(editor.locator('.view-lines')).toContainText('Changed outside.')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Keep this draft.')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  await fs.writeFile(path.join(directory, 'RENAMED.md'), 'Second outside change.\n')
  await expect(page.locator('.file-editor__conflict')).toBeVisible()
  await expect(editor.locator('.view-lines')).toContainText('Keep this draft.')
  await row('external.txt').click()
  await tree.press('Delete')
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(row('external.txt')).toHaveCount(0)
  await expect.poll(() => fs.access(path.join(directory, 'external.txt')).then(() => true, () => false)).toBe(false)
  expect(await fs.readFile(path.join(directory, 'src', 'RENAMED.md'), 'utf8')).toBe(afterUndo)
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test('file editor distinguishes external deletion and recovers without losing unsaved edits', async ({ buddy }) => {
  const instance = await buddy.createInstance('file-missing-recovery')
  const directory = path.join(instance.home, 'documents')
  const source = path.join(directory, 'README.md')
  await fs.mkdir(directory, { recursive: true })
  await fs.writeFile(source, 'Original document.\n')
  const { app, page, diagnostics } = await instance.launch()
  await createSpace(app, page, directory)
  await page.evaluate(() => window.lexoraDesktop.settings.update({ desktop: { contextPanelMode: 'independent' } }))
  const toggle = page.getByTestId('context-panel-toggle')
  if (await toggle.getAttribute('aria-expanded') === 'false')
    await toggle.click()
  await page.getByTestId('task-context-open-files').click()
  await page.getByTestId('file-space-picker').getByRole('button', { name: /文件树验收/ }).click()
  await page.getByTestId('context-file-tree').locator('[data-path="README.md"]').click()
  await page.getByTestId('document-mode-edit').click()
  const editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Original document.')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Keep this draft.')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  await fs.rm(source)
  await expect(page.locator('.file-editor__error')).toContainText('文件已被移动或删除')
  await expect(editor.locator('.view-lines')).toContainText('Keep this draft.')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  await fs.writeFile(source, 'Restored outside.\n')
  await expect(page.locator('.file-editor__error')).toHaveCount(0)
  await expect(page.locator('.file-editor__conflict')).toContainText('Restored outside.')
  await expect(editor.locator('.view-lines')).toContainText('Keep this draft.')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  expect(await fs.readFile(source, 'utf8')).toBe('Restored outside.\n')
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test('copy path uses native clipboard text independently from file copy and cut', async ({ buddy }) => {
  const instance = await buddy.createInstance('file-copy-path')
  const directory = path.join(instance.home, process.platform === 'win32' ? 'documents' : 'documents\\draft')
  await Promise.all(['资料', 'copied', 'moved'].map(name => fs.mkdir(path.join(directory, name), { recursive: true })))
  const name = '合同 草稿.txt'
  const source = path.join(directory, '资料', name)
  await fs.writeFile(source, 'clipboard contract')
  const { app, page, diagnostics } = await instance.launch()
  await createSpace(app, page, directory)
  await page.evaluate(() => window.lexoraDesktop.settings.update({ desktop: { contextPanelMode: 'independent' } }))
  const toggle = page.getByTestId('context-panel-toggle')
  if (await toggle.getAttribute('aria-expanded') === 'false')
    await toggle.click()
  await page.getByTestId('task-context-open-files').click()
  await page.getByTestId('file-space-picker').getByRole('button', { name: /文件树验收/ }).click()
  const tree = page.getByTestId('context-file-tree')
  const row = name => tree.locator(`[data-path="${name}"]`)
  await row('资料').click()
  await expect(row(`资料/${name}`)).toBeVisible()
  async function command(target, label) {
    await row(target).click({ button: 'right' })
    const menu = page.locator('.n-dropdown-menu:visible')
    await menu.getByText(label, { exact: true }).click()
    await expect(menu).toBeHidden()
  }
  const readClipboard = () => app.evaluate(({ clipboard }) => clipboard.readText())
  await app.evaluate(({ clipboard }) => clipboard.writeText('preserve existing text'))
  await command(`资料/${name}`, '复制')
  expect(await readClipboard()).toBe('preserve existing text')
  await command(`资料/${name}`, '复制路径')
  await expect.poll(readClipboard).toBe(source)
  await command('资料', '复制路径')
  await expect.poll(readClipboard).toBe(path.join(directory, '资料'))
  await command('copied', '粘贴')
  await expect.poll(() => fs.readFile(path.join(directory, 'copied', name), 'utf8')).toBe('clipboard contract')
  expect(await fs.readFile(source, 'utf8')).toBe('clipboard contract')
  await command(`资料/${name}`, '剪切')
  expect(await readClipboard()).toBe(path.join(directory, '资料'))
  await command('copied', '复制路径')
  await command('moved', '粘贴')
  await expect.poll(() => fs.readFile(path.join(directory, 'moved', name), 'utf8')).toBe('clipboard contract')
  await expect.poll(() => fs.access(source).then(() => true, () => false)).toBe(false)
  expect(await readClipboard()).toBe(path.join(directory, 'copied'))
  const target = await page.evaluate(async () => {
    const spaces = await window.lexoraDesktop.localChat.spaces.list()
    const space = spaces.find(space => space.name === '文件树验收')
    return { spaceId: space.id, directoryId: space.primaryDirectory.id, revision: space.primaryDirectory.revision, path: 'copied/合同 草稿.txt' }
  })
  await app.evaluate(({ clipboard }) => clipboard.writeText('unchanged on denied path'))
  for (const input of [{ ...target, revision: target.revision + 1 }, { ...target, path: '../outside.txt' }]) {
    await expect(page.evaluate(input => window.lexoraDesktop.localChat.spaces.copyFilePath(input), input)).rejects.toThrow()
    expect(await readClipboard()).toBe('unchanged on denied path')
  }
  await page.evaluate(spaceId => window.lexoraDesktop.localChat.spaces.delete(spaceId), target.spaceId)
  await expect(page.evaluate(input => window.lexoraDesktop.localChat.spaces.copyFilePath(input), target)).rejects.toThrow()
  expect(await readClipboard()).toBe('unchanged on denied path')
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test('file loading stays local while directories and documents arrive independently', async ({ buddy }) => {
  const instance = await buddy.createInstance('file-loading')
  const directory = path.join(instance.home, 'documents')
  await fs.mkdir(path.join(directory, 'src'), { recursive: true })
  await fs.writeFile(path.join(directory, 'README.md'), 'Available while the folder loads.\n')
  await fs.writeFile(path.join(directory, 'src', 'index.ts'), 'export const ready = true\n')
  const { app, page, diagnostics } = await instance.launch()
  await page.setViewportSize({ width: 1440, height: 960 })
  await createSpace(app, page, directory)
  await page.evaluate(() => window.lexoraDesktop.settings.update({ desktop: { contextPanelMode: 'independent' } }))
  await app.evaluate(({ ipcMain }) => {
    const list = 'lexora:buddy:space-files:list'
    const read = 'lexora:buddy:spaces:document:read'
    globalThis.fileLoadingGates = new Map([
      [`${list}:`, Promise.withResolvers()],
      [`${list}:src`, Promise.withResolvers()],
      [`${read}:README.md`, Promise.withResolvers()],
    ])
    for (const channel of [list, read]) {
      const original = ipcMain._invokeHandlers.get(channel)
      ipcMain.removeHandler(channel)
      ipcMain.handle(channel, async (event, input) => {
        await globalThis.fileLoadingGates.get(`${channel}:${input.path}`)?.promise
        return original(event, input)
      })
    }
  })
  const toggle = page.getByTestId('context-panel-toggle')
  if (await toggle.getAttribute('aria-expanded') === 'false')
    await toggle.click()
  await page.getByTestId('task-context-open-files').click()
  await page.getByTestId('file-space-picker').getByRole('button', { name: /文件树验收/ }).click()
  const tree = page.getByTestId('context-file-tree')
  const placeholder = page.locator('.workspace-explorer .desktop-file-loading__placeholder')
  await expect(tree).toHaveAttribute('aria-busy', 'true')
  await expect(placeholder).toBeVisible()
  await app.evaluate(() => globalThis.fileLoadingGates.get('lexora:buddy:space-files:list:').resolve())
  const src = tree.locator('[data-path="src"]')
  const readme = tree.locator('[data-path="README.md"]')
  await expect(readme).toBeVisible()
  await expect(placeholder).toHaveCount(0)
  await src.click()
  await expect(src).toHaveAttribute('aria-busy', 'true')
  await expect(src.locator('.is-loading, .explorer-loading')).toBeVisible()
  await expect(readme).toBeVisible()
  await readme.click()
  await expect(page.locator('.desktop-file-loading__placeholder')).toBeVisible()
  await app.evaluate(() => globalThis.fileLoadingGates.get('lexora:buddy:spaces:document:read:README.md').resolve())
  await expect(page.locator('.file-editor')).toContainText('Available while the folder loads.')
  await expect(src).toHaveAttribute('aria-busy', 'true')
  await src.click()
  await page.getByTestId('context-add-tab').click()
  await page.getByRole('menuitem', { name: '文件', exact: true }).click()
  await page.getByTestId('file-space-picker').getByRole('button', { name: /文件树验收/ }).click()
  await expect(src).not.toHaveAttribute('aria-busy', 'true')
  await src.click()
  await expect(src).toHaveAttribute('aria-busy', 'true')
  await app.evaluate(() => globalThis.fileLoadingGates.get('lexora:buddy:space-files:list:src').resolve())
  await expect(tree.locator('[data-path="src/index.ts"]')).toBeVisible()
  await page.getByTestId('task-context-panel').getByRole('tab', { name: '文件', exact: true }).first().click()
  await expect(src).not.toHaveAttribute('aria-busy', 'true')
  await expect(tree.locator('[data-path="src/index.ts"]')).toHaveCount(0)
  await src.click()
  await expect(tree.locator('[data-path="src/index.ts"]')).toBeVisible()
  await fs.writeFile(path.join(directory, 'src', 'external.ts'), 'export const external = true\n')
  await expect(tree.locator('[data-path="src/external.ts"]')).toBeVisible()
  await expect(page.locator('.file-editor')).toContainText('Available while the folder loads.')
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test('markdown preview resolves document images and retries failed media in place', async ({ buddy }) => {
  const instance = await buddy.createInstance('markdown-images')
  const directory = path.join(instance.home, 'documents')
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="96" height="64"><rect width="96" height="64" fill="#4f80c0"/></svg>'
  await fs.mkdir(path.join(directory, 'guides'), { recursive: true })
  await fs.mkdir(path.join(directory, '截图'))
  await fs.writeFile(path.join(directory, '截图', 'a b.svg'), svg)
  await fs.writeFile(path.join(directory, '截图', 'later.svg'), 'invalid image')
  await fs.writeFile(path.join(directory, 'guides', 'readme.md'), '# Image guide\n\n![Diagram](../截图/a%20b.svg)\n\n![Later](../截图/later.svg)')
  const { app, page, diagnostics } = await instance.launch()
  await createSpace(app, page, directory)
  await page.evaluate(() => window.lexoraDesktop.settings.update({ desktop: { contextPanelMode: 'independent' } }))
  const toggle = page.getByTestId('context-panel-toggle')
  if (await toggle.getAttribute('aria-expanded') === 'false')
    await toggle.click()
  await page.getByTestId('task-context-open-files').click()
  await page.getByTestId('file-space-picker').getByRole('button', { name: /文件树验收/ }).click()
  const tree = page.getByTestId('context-file-tree')
  await tree.locator('[data-path="guides"]').click()
  await tree.locator('[data-path="guides/readme.md"]').click()
  await page.getByTestId('document-mode-preview').click()
  const preview = page.locator('.desktop-document-content__markdown:visible')
  await expect(preview.getByRole('heading', { name: 'Image guide' })).toBeVisible()
  await expect.poll(() => preview.getByAltText('Diagram').evaluate(element => element.naturalWidth)).toBe(96)
  const error = preview.getByRole('status').filter({ hasText: '图片加载失败' })
  await expect(error).toBeVisible()
  await expect(preview.getByAltText('Later')).toHaveCount(0)
  await fs.writeFile(path.join(directory, '截图', 'later.svg'), svg)
  await error.getByRole('button', { name: '重试', exact: true }).click()
  await expect.poll(() => preview.getByAltText('Later').evaluate(element => element.naturalWidth)).toBe(96)
  await expect(preview.getByRole('status')).toHaveCount(0)
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})
