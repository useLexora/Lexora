import fs from 'node:fs/promises'
import path from 'node:path'
import { expect, test } from '../fixtures/electron.mjs'

async function createSpace(app, page, directory) {
  await app.evaluate(({ dialog }, directory) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] })
  }, directory)
  const section = page.locator('.desktop-task-sidebar__spaces')
  await section.locator('.desktop-task-sidebar__section-heading').hover()
  await section.locator('.desktop-task-sidebar__section-add').click()
  const spaceDialog = page.locator('.desktop-space-dialog')
  await spaceDialog.getByPlaceholder('输入空间名称').fill('文件树验收')
  await spaceDialog.getByRole('button', { name: '选择目录', exact: true }).click()
  await spaceDialog.getByRole('button', { name: '确定', exact: true }).click()
  await expect(spaceDialog).toBeHidden()
}

test('file explorer preserves edits and undo through rename, rejects copy conflicts and watches external changes', async ({ buddy }, testInfo) => {
  const instance = await buddy.createInstance('file-explorer')
  const directory = path.join(instance.home, 'documents')
  await fs.mkdir(path.join(directory, 'src'), { recursive: true })
  await fs.writeFile(path.join(directory, 'README.md'), 'Original document.\n')
  await Promise.all(Array.from({ length: 251 }, (_, index) => fs.writeFile(path.join(directory, 'src', `${String(index).padStart(3, '0')}.ts`), 'export const value = 1\n')))
  const { app, page, diagnostics } = await instance.launch()
  await createSpace(app, page, directory)
  const space = page.locator('.desktop-task-space-row').filter({ hasText: '文件树验收' })
  await space.hover()
  await space.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.locator('.n-dropdown-menu:visible').getByText('新任务', { exact: true }).click()
  await page.locator('.desktop-workbench-area__tasks .tiptap').click()
  await page.keyboard.press('Control+Shift+P')
  await page.getByPlaceholder('输入命令名称').fill('文件')
  await page.getByPlaceholder('输入命令名称').press('Enter')
  const tree = page.getByTestId('context-file-tree')
  const row = name => tree.locator(`[data-path="${name}"]`)
  await expect(row('README.md')).toBeVisible()
  await page.getByTestId('context-panel-maximize').click()
  await row('src').click()
  await expect(row('src/000.ts')).toBeVisible()
  await tree.press('End')
  await expect(tree).toHaveAttribute('aria-activedescendant', await row('README.md').getAttribute('id'))
  await tree.press('ArrowUp')
  await expect(row('src/250.ts')).toBeVisible()
  await tree.press('Home')
  await tree.press('ArrowLeft')
  await row('README.md').click()
  await page.getByTestId('document-mode-edit').click()
  let editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Original document.')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Unsaved change.\n')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  async function rename() {
    await row('README.md').click({ button: 'right' })
    await page.locator('.n-dropdown-menu:visible').getByText('重命名', { exact: true }).click()
    const modal = page.locator('.explorer-name-dialog')
    await modal.getByRole('textbox', { name: '名称' }).fill('RENAMED.md')
    await modal.getByRole('button', { name: '确定', exact: true }).click()
  }
  await rename()
  await page.locator('.n-dialog').filter({ hasText: '先保存打开的文件' }).getByRole('button', { name: '取消', exact: true }).click()
  await expect(row('README.md')).toBeVisible()
  expect(await fs.readFile(path.join(directory, 'README.md'), 'utf8')).toBe('Original document.\n')
  await rename()
  await page.getByRole('button', { name: '保存并继续', exact: true }).click()
  await expect(row('RENAMED.md')).toBeVisible()
  await expect.poll(() => fs.readFile(path.join(directory, 'RENAMED.md'), 'utf8')).toContain('Unsaved change.')
  await expect.poll(() => fs.access(path.join(directory, 'README.md')).then(() => true, () => false)).toBe(false)
  editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Unsaved change.')
  const beforeUndo = await fs.readFile(path.join(directory, 'RENAMED.md'), 'utf8')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+z')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  await page.keyboard.press('Control+s')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'false')
  const afterUndo = await fs.readFile(path.join(directory, 'RENAMED.md'), 'utf8')
  expect(afterUndo).not.toBe(beforeUndo)
  await row('RENAMED.md').click()
  await tree.press('Control+c')
  await row('src').click()
  await tree.press('Control+v')
  await expect.poll(() => fs.readFile(path.join(directory, 'src', 'RENAMED.md'), 'utf8').catch((error) => {
    if (error.code === 'ENOENT')
      return null
    throw error
  })).toBe(afterUndo)
  await tree.press('Control+v')
  await expect(page.locator('.workspace-explorer [role="alert"]')).toContainText('目标已存在')
  expect(await fs.readFile(path.join(directory, 'src', 'RENAMED.md'), 'utf8')).toBe(afterUndo)
  await page.getByRole('button', { name: '全部折叠', exact: true }).click()
  await fs.writeFile(path.join(directory, 'external.txt'), 'watched')
  await expect(row('external.txt')).toBeVisible()
  await row('RENAMED.md').click()
  await page.getByTestId('document-mode-edit').click()
  editor = page.getByTestId('workbench-text-editor')
  await expect(editor.locator('.view-lines')).toContainText('Original document.')
  await fs.writeFile(path.join(directory, 'RENAMED.md'), 'Changed outside.\n')
  await expect(editor.locator('.view-lines')).toContainText('Changed outside.')
  await editor.locator('.view-lines').click()
  await page.keyboard.press('Control+End')
  await page.keyboard.insertText('Keep this draft.')
  await expect(page.locator('.file-editor')).toHaveAttribute('data-dirty', 'true')
  await fs.writeFile(path.join(directory, 'RENAMED.md'), 'Second outside change.\n')
  await expect(page.locator('.file-editor__conflict')).toBeVisible()
  await expect(editor.locator('.view-lines')).toContainText('Keep this draft.')
  await page.screenshot({ path: testInfo.outputPath('explorer.png') })
  await row('external.txt').click()
  await tree.press('Delete')
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(row('external.txt')).toHaveCount(0)
  await expect.poll(() => fs.access(path.join(directory, 'external.txt')).then(() => true, () => false)).toBe(false)
  expect(await fs.readFile(path.join(directory, 'src', 'RENAMED.md'), 'utf8')).toBe(afterUndo)
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test.describe('development file explorer', () => {
  test.use({ developmentRenderer: true })

  test('space picker opens files and keeps menus, tabs and panel resizing responsive', async ({ buddy }, testInfo) => {
    const instance = await buddy.createInstance('file-explorer-dev')
    const directory = path.join(instance.home, 'documents')
    await fs.mkdir(directory)
    await fs.writeFile(path.join(directory, 'README.md'), 'Development file preview.\n')
    const { app, page, diagnostics } = await instance.launch()
    await page.setViewportSize({ width: 1440, height: 960 })
    await createSpace(app, page, directory)
    await page.evaluate(() => window.lexoraDesktop.settings.update({ desktop: { contextPanelMode: 'independent', theme: { id: 'lexora.themes.classic-light' } } }))
    const toggle = page.getByTestId('context-panel-toggle')
    if (await toggle.getAttribute('aria-expanded') === 'false')
      await toggle.click()
    await page.getByTestId('task-context-open-files').click()
    const picker = page.getByTestId('file-space-picker')
    await picker.getByRole('button', { name: /文件树验收/ }).click()
    const panel = page.getByTestId('task-context-panel')
    const file = page.getByTestId('context-file-tree').locator('[data-path="README.md"]')
    await expect(file).toBeVisible()
    await expect(page.getByTestId('task-context-open-files')).toBeHidden()
    await file.click()
    await expect(panel).toContainText('Development file preview.')
    await file.click({ button: 'right' })
    const menu = page.locator('.n-dropdown-menu:visible')
    await expect(menu.getByText('重命名', { exact: true })).toBeVisible()
    await expect(menu.getByText('删除', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '全部折叠', exact: true }).click()
    await expect(menu).toHaveCount(0)
    await file.click({ button: 'right' })
    await menu.getByText('刷新', { exact: true }).click()
    await expect(menu).toHaveCount(0)
    await expect(file).toBeVisible()

    async function dragWider(handle, element, delta) {
      const width = () => element.evaluate(element => element.getBoundingClientRect().width)
      const before = await width()
      const bounds = await handle.boundingBox()
      await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 100)
      await page.mouse.down()
      await page.mouse.move(bounds.x + bounds.width / 2 + delta, bounds.y + 100, { steps: 8 })
      await page.mouse.up()
      await expect.poll(width).toBeGreaterThan(before)
    }
    const context = page.locator('.desktop-workbench-layout__context')
    await dragWider(page.getByTestId('workbench-context-resizer'), context, -72)
    await dragWider(page.locator('.desktop-context-split__separator'), page.locator('.desktop-context-split > aside'), -40)
    await dragWider(page.getByTestId('workbench-sidebar-resizer'), page.locator('.desktop-workbench-layout__sidebar'), 32)

    await page.getByTestId('context-add-tab').click()
    await page.getByRole('menuitem', { name: '文件', exact: true }).click()
    await picker.getByRole('button', { name: /文件树验收/ }).click()
    await expect(panel.getByRole('tab', { name: '文件', exact: true })).toHaveCount(2)
    await expect(file).toBeVisible()
    await panel.getByRole('tab', { name: '文件', exact: true }).first().click()
    await expect(panel).toContainText('Development file preview.')
    await page.screenshot({ path: testInfo.outputPath('development-files-and-resize.png') })
    await panel.getByRole('button', { name: '关闭文件', exact: true }).last().click()
    await expect(panel.getByRole('tab', { name: '文件', exact: true })).toHaveCount(1)
    await expect(file).toBeVisible()
    expect(diagnostics.console.filter(item => item.type === 'pageerror' || /\[Vue warn\]|\[naive\//.test(item.text))).toEqual([])
  })
})
