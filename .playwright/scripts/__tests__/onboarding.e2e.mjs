test('first-run setup saves the buddy and preferences, supports language and layout changes, and stays complete after restart', async ({ buddy }) => {
  const instance = await buddy.createInstance('onboarding')
  await fs.unlink(path.join(instance.home, 'config.toml'))
  let { app, page, diagnostics } = await instance.launch()
  expect(await page.evaluate(() => window.lexoraDesktop.settings.get())).toMatchObject({ desktop: { onboardingCompleted: false, theme: { id: 'system' } } })
  await page.evaluate(() => window.lexoraDesktop.settings.update({ desktop: { language: 'zh-CN', theme: { id: 'lexora.themes.classic-light' } } }))
  let screen = page.getByTestId('desktop-onboarding')
  await expect(screen.getByRole('heading', { name: '先认识你的伙伴' })).toBeVisible()
  await expect(screen.getByRole('button', { name: '退出引导', exact: true })).toHaveCount(0)
  await screen.getByRole('button', { name: 'DeepSeek', exact: true }).click()
  await screen.getByLabel('伙伴名称', { exact: true }).fill('小澜')
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(screen.getByRole('heading', { name: '让伙伴开始思考' })).toBeVisible()
  expect(await page.evaluate(async () => {
    const catalog = await window.lexoraDesktop.localChat.buddies.list()
    return catalog.buddies.find(buddy => buddy.id === catalog.defaultBuddyId)
  })).toMatchObject({ name: '小澜', avatar: 'preset:actor-deepseek' })
  await screen.getByRole('button', { name: '暂时跳过', exact: true }).click()
  await expect(screen.getByRole('heading', { name: '按你的习惯开始' })).toBeVisible()
  await screen.getByText('沉浸', { exact: true }).click()
  await expect(screen.getByRole('radio', { name: '沉浸', exact: false })).toBeChecked()
  await screen.getByRole('switch', { name: '显示桌面伙伴', exact: true }).click()
  await screen.getByLabel('外观', { exact: true }).click()
  await page.locator('.n-base-select-option').getByText('深色', { exact: true }).click()
  await screen.getByLabel('界面语言', { exact: true }).click()
  await page.locator('.n-base-select-option').getByText('English', { exact: true }).click()
  await expect(screen.getByRole('heading', { name: 'Make yourself at home' })).toBeVisible()
  await app.evaluate(({ ipcMain }) => {
    const channel = 'lexora:settings:update'
    const original = ipcMain._invokeHandlers.get(channel)
    ipcMain.removeHandler(channel)
    ipcMain.handle(channel, (event, patch) => {
      ipcMain.removeHandler(channel)
      ipcMain.handle(channel, original)
      if (patch.desktop?.onboardingCompleted)
        throw new Error('Isolated onboarding save failure')
      return original(event, patch)
    })
  })
  await screen.getByRole('button', { name: 'Get started', exact: true }).click()
  await expect(screen.getByRole('alert')).toContainText('Could not finish saving')
  expect((await page.evaluate(() => window.lexoraDesktop.settings.get())).desktop.onboardingCompleted).toBe(false)
  await expect(screen.getByRole('radio', { name: 'Immersive', exact: false })).toBeChecked()
  await screen.getByRole('button', { name: 'Get started', exact: true }).click()
  await expect(screen).toBeHidden()
  await expect(page.locator('.desktop-shell')).toHaveAttribute('data-navigation-layout', 'immersive')
  const config = await page.evaluate(() => window.lexoraDesktop.settings.get())
  expect(config).toMatchObject({ desktop: { language: 'en-US', onboardingCompleted: true, navigationLayout: 'immersive', theme: { id: 'lexora.themes.classic-dark' } }, pet: { enabled: false } })
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
  await instance.stop()
  ;({ page, diagnostics } = await instance.launch())
  screen = page.getByTestId('desktop-onboarding')
  await expect(screen).toHaveCount(0)
  await expect(page.locator('.desktop-shell')).toHaveAttribute('data-navigation-layout', 'immersive')
  expect(await page.evaluate(() => window.lexoraDesktop.settings.get())).toEqual(config)
  expect(diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test('onboarding keeps one upload slot and preserves saved profile when setup is interrupted', async ({ buddy }) => {
  const instance = await buddy.createInstance('onboarding-upload')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nonboarding_completed=false\nlanguage="zh-CN"\n[pet]\nenabled=false\n')
  let { page } = await instance.launch()
  let screen = page.getByTestId('desktop-onboarding')
  const upload = screen.locator('input[type="file"]')
  await upload.setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') })
  await expect(screen.getByRole('alert')).toBeVisible()
  const image = path.resolve('apps/buddy/src/modules/buddies/assets/avatars/actor-chatgpt.webp')
  await upload.setInputFiles(image)
  await expect(screen.getByRole('alert')).toHaveCount(0)
  await upload.setInputFiles(path.resolve('apps/buddy/src/modules/buddies/assets/avatars/actor-claude.webp'))
  await expect(screen.getByRole('group', { name: '伙伴头像' }).getByRole('button')).toHaveCount(5)
  await screen.getByLabel('伙伴名称', { exact: true }).fill('同行')
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(screen.getByRole('heading', { name: '让伙伴开始思考' })).toBeVisible()
  const profile = await page.evaluate(async () => {
    const catalog = await window.lexoraDesktop.localChat.buddies.list()
    return catalog.buddies.find(buddy => buddy.id === catalog.defaultBuddyId)
  })
  expect(profile.customAvatars).toHaveLength(1)
  expect(profile.avatar).toBe(profile.customAvatars[0])
  await instance.stop()
  ;({ page } = await instance.launch())
  screen = page.getByTestId('desktop-onboarding')
  await expect(screen.getByLabel('伙伴名称', { exact: true })).toHaveValue('同行')
  await expect(screen.getByRole('button', { name: '自定义', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.evaluate(async () => {
    const api = window.lexoraDesktop.localChat.buddies
    const catalog = await api.list()
    const buddy = catalog.buddies.find(buddy => buddy.id === catalog.defaultBuddyId)
    await api.update({ buddyId: buddy.id, expectedRevision: buddy.revision, name: '另一处修改' })
  })
  await screen.getByLabel('伙伴名称', { exact: true }).fill('我的改名')
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(screen.getByRole('alert')).toContainText('伙伴资料已发生变化')
  await screen.getByRole('button', { name: '重新载入', exact: true }).click()
  await expect(screen.getByLabel('伙伴名称', { exact: true })).toHaveValue('另一处修改')
})

test('onboarding uses the connected service catalog and persists a chosen default model', async ({ buddy }) => {
  const instance = await buddy.createInstance('onboarding-model')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nonboarding_completed=false\nlanguage="zh-CN"\n[pet]\nenabled=false\n')
  const desktop = await instance.launch()
  const { page } = desktop
  await useSyntheticCredentialStorage(desktop)
  const model = await page.evaluate(async () => {
    const providers = window.lexoraDesktop.localChat.providers
    const provider = await providers.add('openai')
    const stop = providers.onAuthChallenge((challenge) => {
      if (challenge.providerId === provider.id && challenge.type === 'secret')
        void providers.respondToAuth(challenge.challengeId, 'offline-fixture-key')
    })
    try {
      await providers.login(provider.id, 'api_key')
    }
    finally { stop() }
    const model = (await providers.listModels(provider.id))[0]
    await providers.setModelEnabled(provider.id, model.modelId, true)
    await providers.setEnabled(provider.id, true)
    await providers.setDefaultModel(null)
    return model
  })
  await page.reload()
  const screen = page.getByTestId('desktop-onboarding')
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await screen.getByRole('button', { name: /选择模型/ }).click()
  const picker = page.locator('.desktop-model-picker')
  await expect(picker.getByRole('textbox')).toBeVisible()
  await picker.getByRole('textbox').fill(model.modelId)
  await picker.getByRole('menuitemradio').filter({ hasText: model.displayName }).click()
  await expect(picker).toBeHidden()
  await expect.poll(() => page.evaluate(() => window.lexoraDesktop.localChat.providers.getDefaultModel())).toMatchObject({ providerId: model.providerId, modelId: model.modelId })
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await screen.getByRole('button', { name: '开始使用', exact: true }).click()
  await expect(screen).toBeHidden()
  await expect(page.locator('.desktop-model-selector__trigger:visible')).toContainText(model.displayName)
})

test('legacy profiles skip setup, and About reopens it without losing saved preferences or unsaved draft boundaries', async ({ buddy }) => {
  const instance = await buddy.createInstance('onboarding-reopen')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nlanguage="zh-CN"\nnavigation_layout="compact"\ntheme="dark"\n[pet]\nenabled=false\n')
  let { page } = await instance.launch()
  await page.evaluate(() => window.location.hash = '/settings/about')
  const reopen = page.getByRole('button', { name: '打开引导', exact: true })
  const screen = page.getByTestId('desktop-onboarding')
  const readBuddy = () => page.evaluate(async () => {
    const catalog = await window.lexoraDesktop.localChat.buddies.list()
    return catalog.buddies.find(buddy => buddy.id === catalog.defaultBuddyId)
  })
  await expect(screen).toHaveCount(0)
  await expect(page.locator('.desktop-shell')).toHaveAttribute('data-navigation-layout', 'compact')
  const config = await page.evaluate(() => window.lexoraDesktop.settings.get())
  expect(config).toMatchObject({ desktop: { language: 'zh-CN', navigationLayout: 'compact', theme: { id: 'lexora.themes.classic-dark' } }, pet: { enabled: false } })
  const profile = await readBuddy()
  await reopen.click()
  await expect(screen.getByLabel('伙伴名称', { exact: true })).toHaveValue(profile.name)
  await screen.getByLabel('伙伴名称', { exact: true }).fill('尚未保存的名称')
  await screen.getByRole('button', { name: '退出引导', exact: true }).click()
  await expect(reopen).toBeVisible()
  expect(await readBuddy()).toEqual(profile)
  expect(await page.evaluate(() => window.lexoraDesktop.settings.get())).toEqual(config)
  await page.evaluate(async () => {
    const api = window.lexoraDesktop.localChat.buddies
    const catalog = await api.list()
    const buddy = catalog.buddies.find(buddy => buddy.id === catalog.defaultBuddyId)
    await api.update({ buddyId: buddy.id, expectedRevision: buddy.revision, name: '当前伙伴', avatar: 'preset:actor-claude' })
    await window.lexoraDesktop.settings.update({ desktop: { navigationLayout: 'immersive', autoDownloadUpdates: false } })
  })
  await reopen.click()
  await expect(screen.getByLabel('伙伴名称', { exact: true })).toHaveValue('当前伙伴')
  await expect(screen.getByRole('button', { name: 'Claude', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await screen.getByRole('button', { name: '暂时跳过', exact: true }).click()
  await expect(screen.getByRole('radio', { name: '沉浸', exact: false })).toBeChecked()
  await expect(screen.getByRole('switch', { name: '显示桌面伙伴', exact: true })).not.toBeChecked()
  await screen.getByText('全览', { exact: true }).click()
  await screen.getByRole('button', { name: '退出引导', exact: true }).click()
  expect((await page.evaluate(() => window.lexoraDesktop.settings.get())).desktop.navigationLayout).toBe('immersive')
  await reopen.click()
  await expect(screen.getByLabel('伙伴名称', { exact: true })).toHaveValue('当前伙伴')
  await screen.getByRole('button', { name: '下一步', exact: true }).click()
  await screen.getByRole('button', { name: '暂时跳过', exact: true }).click()
  await expect(screen.getByRole('radio', { name: '沉浸', exact: false })).toBeChecked()
  await screen.getByText('轻简', { exact: true }).click()
  await screen.getByRole('button', { name: '保存并完成', exact: true }).click()
  await expect(reopen).toBeVisible()
  expect(await page.evaluate(() => window.lexoraDesktop.settings.get())).toMatchObject({ desktop: { onboardingCompleted: true, navigationLayout: 'compact', autoDownloadUpdates: false }, pet: { enabled: false } })
  await reopen.click()
  await expect(screen).toBeVisible()
  await instance.stop()
  ;({ page } = await instance.launch())
  await expect(page.getByTestId('desktop-onboarding')).toHaveCount(0)
  await expect(page.locator('.desktop-shell')).toHaveAttribute('data-navigation-layout', 'compact')
  expect(await readBuddy()).toMatchObject({ name: '当前伙伴', avatar: 'preset:actor-claude' })
})
