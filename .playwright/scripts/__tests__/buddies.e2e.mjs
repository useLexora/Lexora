import { expect, test } from '../fixtures/electron.mjs'

async function openBuddies(page) {
  await page.locator('#desktop-app-sidebar nav').getByRole('button', { name: '伙伴', exact: true }).click()
  await expect(page.getByRole('heading', { name: '伙伴配置' })).toBeVisible()
}

test('companion profiles persist through restart and the default stays protected from deletion', async ({ buddy }, testInfo) => {
  const instance = await buddy.createInstance('buddies-catalog')
  let desktop = await instance.launch()
  let { page } = desktop
  await openBuddies(page)
  await page.getByRole('button', { name: '添加伙伴 · 主角', exact: true }).click()
  await expect(page.getByRole('button', { name: '创建伙伴', exact: true })).toBeDisabled()
  await page.getByLabel('名称', { exact: true }).fill('星野')
  await page.getByRole('button', { name: '创建伙伴', exact: true }).click()
  await expect(page.getByRole('heading', { name: '星野', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '编辑资料', exact: true }).click()
  await page.getByLabel('名称', { exact: true }).fill('星野助手')
  await page.getByLabel('简介', { exact: true }).fill('一起整理思路。')
  await page.getByRole('button', { name: '保存更改', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('heading', { name: '星野助手', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '设为默认', exact: true }).click()
  await expect(page.getByTestId('buddy-list').getByRole('link', { name: /星野助手/ })).toContainText('默认')
  await expect(page.getByTestId('buddy-profile-actions').getByRole('button', { name: '删除伙伴', exact: true })).toBeDisabled()
  expect(desktop.diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])

  await instance.stop()
  desktop = await instance.launch()
  page = desktop.page
  await openBuddies(page)
  const list = page.getByTestId('buddy-list')
  const companion = list.getByRole('link', { name: /星野助手/ })
  await expect(companion).toContainText('默认')
  await companion.click()
  await page.getByRole('button', { name: '编辑资料', exact: true }).click()
  await expect(page.getByLabel('名称', { exact: true })).toHaveValue('星野助手')
  await expect(page.getByLabel('简介', { exact: true })).toHaveValue('一起整理思路。')
  await page.getByRole('dialog').getByRole('button', { name: '取消', exact: true }).click()
  await page.screenshot({ animations: 'disabled', path: testInfo.outputPath('companion-restored.png') })
  await list.getByRole('link', { name: /Lexora/ }).click()
  await page.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '设为默认', exact: true }).click()
  await expect(list.getByRole('link', { name: /Lexora/ })).toContainText('默认')
  await companion.click()
  await page.getByTestId('buddy-profile-actions').getByRole('button', { name: '删除伙伴', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除伙伴', exact: true }).click()
  await expect(companion).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Lexora', exact: true })).toBeVisible()
  expect(desktop.diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})

test('cancelling companion profile edits leaves the saved profile unchanged', async ({ buddy }) => {
  const instance = await buddy.createInstance('buddy-profile-cancel')
  const desktop = await instance.launch()
  const { page } = desktop
  await openBuddies(page)
  await page.getByRole('button', { name: '添加伙伴 · 主角', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await page.getByLabel('名称', { exact: true }).fill('未保存的新伙伴')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByTestId('buddy-list').getByRole('link', { name: /未保存的新伙伴/ })).toHaveCount(0)
  await page.getByRole('button', { name: '编辑资料', exact: true }).click()
  const name = page.getByLabel('名称', { exact: true })
  const description = page.getByLabel('简介', { exact: true })
  const savedName = await name.inputValue()
  const savedDescription = await description.inputValue()
  await name.fill('未保存的名称')
  await description.fill('未保存的简介')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('button', { name: '编辑资料', exact: true }).click()
  await expect(name).toHaveValue(savedName)
  await expect(description).toHaveValue(savedDescription)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect(desktop.diagnostics.console.filter(item => item.type === 'pageerror')).toEqual([])
})
