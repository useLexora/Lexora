import fs from 'node:fs/promises'
import path from 'node:path'
import { expect, test } from '../fixtures/electron.mjs'

async function launchRelease(instance) {
  const launched = await instance.launch()
  await launched.app.evaluate(({ app }) => {
    if (app.getName() !== 'Lexora Buddy Test')
      throw new Error('Release previews require an isolated test instance')
    app.getVersion = () => '0.14.0'
  })
  await launched.page.reload()
  return launched
}

async function openFeatures(page) {
  await page.evaluate(() => window.location.hash = '/settings/about')
  await page.locator('.desktop-onboarding-settings').getByRole('button', { name: '查看列表', exact: true }).click()
  await expect(page.locator('.feature-discovery-dialog')).toBeVisible()
}

async function readProfile(page) {
  return page.evaluate(async () => {
    const catalog = await window.lexoraDesktop.localChat.buddies.list()
    return catalog.buddies.find(buddy => buddy.id === catalog.defaultBuddyId)
  })
}

test('dismissed reminders and viewed features survive restart while individual guides leave controls usable', async ({ buddy }) => {
  const instance = await buddy.createInstance('feature-guides')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nlanguage="zh-CN"\n[desktop.feature_discovery]\nversion="0.12.0"\npending=[]\nnotified=[]\n[pet]\nenabled=false\n')
  let { page, app } = await launchRelease(instance)
  const discovery = () => page.evaluate(async () => (await window.lexoraDesktop.settings.get()).desktop.featureDiscovery)
  await expect.poll(discovery).toMatchObject({ version: '0.14.0', pending: ['navigation-layout', 'npc-team'], notified: [] })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].focus())
  await page.locator('.desktop-title-bar').click({ position: { x: 350, y: 16 } })
  const reminder = page.getByTestId('feature-discovery-reminder')
  await expect(reminder).toBeVisible()
  await reminder.getByRole('button', { name: '暂不提醒', exact: true }).click()
  await expect(reminder).toBeHidden()
  await expect.poll(discovery).toMatchObject({ pending: ['navigation-layout', 'npc-team'], notified: ['navigation-layout', 'npc-team'] })
  await openFeatures(page)
  const dialog = page.locator('.feature-discovery-dialog')
  await expect(dialog.getByText('未查看', { exact: true })).toHaveCount(2)
  await dialog.getByRole('button', { name: '定位功能：三种导航布局', exact: true }).click()
  const layout = page.locator('.desktop-navigation-layout-settings')
  const hint = page.locator('.buddy-feature-popover')
  await expect(hint).toBeVisible()
  await expect(layout.getByRole('radio', { name: '全览', exact: false })).toBeChecked()
  await page.keyboard.press('Escape')
  await expect(hint).toBeHidden()
  await page.locator('.buddy-feature-hint').click()
  await expect(hint).toBeVisible()
  await layout.getByText('轻简', { exact: true }).click()
  await expect(page.locator('.desktop-shell')).toHaveAttribute('data-navigation-layout', 'compact')
  await expect(hint).toBeHidden()
  await page.locator('.buddy-feature-hint').click()
  await hint.getByRole('button', { name: '知道了', exact: true }).click()
  await expect(page.locator('.buddy-feature-hint')).toHaveCount(0)
  await expect.poll(discovery).toMatchObject({ pending: ['npc-team'] })
  await instance.stop()
  ;({ page } = await launchRelease(instance))
  await expect(page.getByTestId('feature-discovery-reminder')).toHaveCount(0)
  await openFeatures(page)
  await expect(page.locator('.feature-discovery-dialog').getByText('未查看', { exact: true })).toHaveCount(1)
})

test('new installations establish a release baseline without an extra introduction after onboarding', async ({ buddy }) => {
  const instance = await buddy.createInstance('feature-guides-new')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nonboarding_completed=false\nlanguage="zh-CN"\n[pet]\nenabled=false\n')
  const { page } = await launchRelease(instance)
  await expect.poll(() => page.evaluate(async () => (await window.lexoraDesktop.settings.get()).desktop.featureDiscovery)).toEqual({ version: '0.14.0', pending: [], notified: [] })
  const onboarding = page.getByTestId('desktop-onboarding')
  await onboarding.getByRole('button', { name: '下一步', exact: true }).click()
  await onboarding.getByRole('button', { name: '暂时跳过', exact: true }).click()
  await onboarding.getByRole('button', { name: '开始使用', exact: true }).click()
  await expect(onboarding).toBeHidden()
  await expect(page.getByTestId('feature-discovery-reminder')).toHaveCount(0)
  await openFeatures(page)
  await expect(page.locator('.feature-discovery-dialog [data-feature]')).toHaveCount(2)
  await expect(page.locator('.feature-discovery-dialog').getByText('未查看', { exact: true })).toHaveCount(0)
})

test('automatic feature reminders can be disabled across upgrades without losing manual access', async ({ buddy }) => {
  const instance = await buddy.createInstance('feature-guides-disabled')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nlanguage="zh-CN"\nfeature_announcements_enabled=false\n[desktop.feature_discovery]\nversion="0.12.0"\npending=[]\nnotified=[]\n[pet]\nenabled=false\n')
  let { page, app } = await launchRelease(instance)
  const settings = () => page.evaluate(() => window.lexoraDesktop.settings.get())
  await expect.poll(settings).toMatchObject({ desktop: { featureAnnouncementsEnabled: false, featureDiscovery: { version: '0.14.0', pending: ['navigation-layout', 'npc-team'], notified: [] } } })
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].focus())
  await page.locator('.desktop-title-bar').click({ position: { x: 350, y: 16 } })
  await expect(page.getByTestId('feature-discovery-reminder')).toHaveCount(0)
  await page.evaluate(() => window.location.hash = '/settings/about')
  const toggle = page.getByRole('switch', { name: '版本功能提醒', exact: true })
  await expect(toggle).not.toBeChecked()
  await toggle.click()
  await expect.poll(settings).toMatchObject({ desktop: { featureAnnouncementsEnabled: true } })
  await expect(page.getByTestId('feature-discovery-reminder')).toBeVisible()
  await toggle.click()
  await expect.poll(settings).toMatchObject({ desktop: { featureAnnouncementsEnabled: false } })
  await expect(page.getByTestId('feature-discovery-reminder')).toHaveCount(0)
  await instance.stop()
  ;({ page } = await launchRelease(instance))
  await expect.poll(settings).toMatchObject({ desktop: { featureAnnouncementsEnabled: false } })
  await openFeatures(page)
  await expect(page.locator('.feature-discovery-dialog [data-feature]')).toHaveCount(2)
  await page.locator('.feature-discovery-dialog').getByRole('button', { name: '定位功能：NPC 小队开关', exact: true }).click()
  await expect(page.locator('.buddy-feature-popover')).toBeVisible()
  await expect(page.getByTestId('feature-discovery-reminder')).toHaveCount(0)
})

test('release tours preserve partial progress and unsaved buddy changes when returning or ending', async ({ buddy }) => {
  const instance = await buddy.createInstance('feature-tour')
  await fs.writeFile(path.join(instance.home, 'config.toml'), '[desktop]\nlanguage="zh-CN"\nfeature_announcements_enabled=false\n[desktop.feature_discovery]\nversion="0.12.0"\npending=[]\nnotified=[]\n[pet]\nenabled=false\n')
  const { page } = await launchRelease(instance)
  const discovery = () => page.evaluate(async () => (await window.lexoraDesktop.settings.get()).desktop.featureDiscovery)
  const before = await readProfile(page)
  await openFeatures(page)
  const dialog = page.locator('.feature-discovery-dialog')
  await dialog.getByRole('button', { name: '逐项了解', exact: true }).click()
  const hint = page.locator('.buddy-feature-popover')
  await expect(hint).toHaveAttribute('data-step', 'navigation-layout')
  await expect(hint).toContainText('1 / 3')
  await expect(hint.getByRole('button', { name: '上一步', exact: true })).toHaveCount(0)
  await hint.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'npc-team')
  await expect(hint).toContainText('2 / 3')
  await expect.poll(discovery).toMatchObject({ pending: ['npc-team'] })
  await hint.getByRole('button', { name: '结束引导', exact: true }).click()
  await expect(hint).toHaveCount(0)
  await expect(page.locator('.buddy-feature-hint')).toHaveCount(0)
  expect((await readProfile(page)).settings).toEqual(before.settings)
  await openFeatures(page)
  await expect(dialog.getByText('未查看', { exact: true })).toHaveCount(1)
  await dialog.getByRole('button', { name: '逐项了解', exact: true }).click()
  await hint.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'npc-team')
  await hint.getByRole('button', { name: '上一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'navigation-layout')
  await hint.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'npc-team')
  await hint.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'npc-team-save')
  await expect(hint).toContainText('3 / 3')
  await expect(page.locator('.buddy-settings-save')).toBeDisabled()
  await expect.poll(discovery).toMatchObject({ pending: [] })
  await hint.getByRole('button', { name: '上一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'npc-team')
  await page.locator('.buddy-npc-team-toggle').getByRole('switch').click()
  await page.locator('.buddy-feature-hint').click()
  await hint.getByRole('button', { name: '上一步', exact: true }).click()
  await expect(page.getByText('请先保存或放弃更改，再离开当前页面。', { exact: true })).toBeVisible()
  await expect(hint).toHaveAttribute('data-step', 'npc-team')
  await expect(page.locator('.buddy-npc-team-toggle').getByRole('switch')).toHaveAttribute('aria-checked', String(!before.settings.npcTeamEnabled))
  await hint.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(hint).toHaveAttribute('data-step', 'npc-team-save')
  await expect(page.locator('.buddy-settings-save')).toBeEnabled()
  await hint.getByRole('button', { name: '完成引导', exact: true }).click()
  await expect(hint).toHaveCount(0)
  expect((await readProfile(page)).settings).toEqual(before.settings)
  await page.locator('.buddy-settings-save').click()
  await expect.poll(async () => (await readProfile(page)).settings.npcTeamEnabled).toBe(!before.settings.npcTeamEnabled)
})
